#!/usr/bin/env node
/* The full case studies the plane concept reads (/lab/scroll-concepts/
 * g-plane.html), taken straight from their data files, 25 Sept 2026.
 *
 * His question: "would we transition a full case study 'down' like the
 * mini ivy park one so everything feels 'connected'?" To show that
 * honestly the study going down has to be the study, every section in
 * order, in his words, so this reads src/data/<slug>-case-study.ts
 * itself rather than retyping it. The files are TypeScript with only type
 * imports, so the compiler's transpileModule turns each into plain
 * JavaScript and a tiny module shim evaluates it.
 *
 * Every picture a study names gets its real size from
 * src/data/image-dimensions.ts (the registry the site's own renderer
 * uses), so the concept can size a plate honestly. A picture missing from
 * the registry is reported and left out rather than guessed.
 *
 *     node scripts/lib/scroll-concepts-studies.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(import.meta.url);
const ts = require(path.join(ROOT, "node_modules/typescript"));

const load = (rel) => {
  const src = fs.readFileSync(path.join(ROOT, rel), "utf8");
  const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const module = { exports: {} };
  new Function("module", "exports", "require", js)(module, module.exports, () => ({}));
  return module.exports;
};

const { imageDimensions } = load("src/data/image-dimensions.ts");
const SLUGS = { "ivy-park": "ivyParkCaseStudy", "hill-country-kitchen": null, "robert-rodriguez": null };
const out = {}, missing = [];
for (const slug of Object.keys(SLUGS)) {
  const mod = load(`src/data/${slug}-case-study.ts`);
  const study = Object.values(mod).find((v) => v && typeof v === "object" && v.slug === slug);
  if (!study) throw new Error("no study object in " + slug);
  /* every picture it names, with its size */
  const dims = {};
  const walk = (v) => {
    if (typeof v === "string" && /^\/case-studies\/.+\.(jpe?g|png|webp|avif)$/i.test(v)) {
      if (imageDimensions[v]) dims[v] = imageDimensions[v]; else missing.push(v);
    } else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === "object") Object.values(v).forEach(walk);
  };
  walk(study);
  out[slug] = { ...study, dims };
}
/* ── A FULL-BLEED PICTURE FOR EVERY STUDY ─────────────────────────────
   A picture can fill the glass only if it has the pixels: on a 2x screen
   1512 CSS pixels wide that is 3,024, so a candidate must be at least
   3,000 wide and landscape. The study's own heroes come first, in the
   order the study shows them; failing those, its widest landscape
   picture. A study with none gets none, and the concept does not
   stretch a smaller one. */
const bleeds = {};
for (const f of fs.readdirSync(path.join(ROOT, "src/data")).filter((x) => x.endsWith("-case-study.ts"))) {
  const slug = f.replace("-case-study.ts", "");
  let study;
  try { study = Object.values(load("src/data/" + f)).find((v) => v && typeof v === "object" && Array.isArray(v.sections)); } catch (e) { continue; }
  if (!study) continue;
  const ok = (src) => { const d = imageDimensions[src]; return d && d[0] >= 3000 && d[0] > d[1] * 1.15; };
  const heroes = study.sections.filter((x) => x.type === "hero" && x.image).map((x) => ({ src: x.image, alt: x.alt || "" }));
  let pick = heroes.find((h) => ok(h.src));
  if (!pick) {
    const all = [];
    const walk = (v) => { if (typeof v === "string" && ok(v)) all.push(v); else if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === "object") Object.values(v).forEach(walk); };
    walk(study.sections);
    all.sort((a, b) => imageDimensions[b][0] - imageDimensions[a][0]);
    if (all[0]) pick = { src: all[0], alt: "" };
  }
  if (pick) bleeds[study.slug] = { src: pick.src, alt: pick.alt, w: imageDimensions[pick.src][0], h: imageDimensions[pick.src][1] };
}

const file = path.join(ROOT, "public/lab/scroll-concepts/studies.js");
fs.writeFileSync(file, "/* generated by scripts/lib/scroll-concepts-studies.mjs from src/data; do not edit by hand */\nwindow.STUDIES_FULL = "
  + JSON.stringify(out) + ";\nwindow.BLEEDS = " + JSON.stringify(bleeds) + ";\n");
console.log("full-bleed pictures for", Object.keys(bleeds).length, "studies:", Object.keys(bleeds).join(", "));
console.log("wrote", path.relative(ROOT, file), fs.statSync(file).size, "bytes;",
  Object.entries(out).map(([k, v]) => `${k} ${v.sections.length} sections, ${Object.keys(v.dims).length} pictures`).join("; "));
if (missing.length) console.log("not in the registry, left out:", missing);

/* ── EVERY PICTURE A STUDY HOLDS, FOR CONCEPT H ───────────────────────
   Concept H (/lab/scroll-concepts/h-words.html) hangs each line's
   pictures in boxes of three sizes: a column at about 590 CSS pixels, a
   held picture at about 920, and the full glass at 1,512. Which picture
   fits which box is decided by its real width (half of it is the largest
   honest CSS width on a 2x screen), so every study's pictures go out with
   their sizes, homepage picture first, then the study's own in the order
   it shows them.
   Left out: anything under 1,100 wide (too small for the smallest box),
   and any PNG or WebP that carries transparency, because a box that shows
   the paper through a picture reads as the picture failing to fill it
   (the cover reel's rule, CLAUDE.md). */
const hasAlpha = (src) => {
  const file = path.join(ROOT, "public", src);
  let b;
  try { b = fs.readFileSync(file).subarray(0, 1 << 16); } catch (e) { return true; }
  if (/\.png$/i.test(src)) {
    const type = b[25];
    if (type === 4 || type === 6) return true;
    const trns = b.indexOf("tRNS"), idat = b.indexOf("IDAT");
    return trns !== -1 && (idat === -1 || trns < idat);
  }
  if (/\.webp$/i.test(src)) {
    const kind = b.toString("ascii", 12, 16);
    if (kind === "VP8X") return (b[20] & 0x10) !== 0;
    return kind === "VP8L";
  }
  return false;
};
const { projects } = load("src/data/projects.ts");
const homePic = {};
for (const p of projects || []) {
  const slug = (p.href || "").replace("/case-studies/", "");
  const src = (p.image || "").split("?")[0];
  if (slug && imageDimensions[src]) homePic[slug] = { src, alt: p.title || "" };
}
const pictures = {}, dropped = { small: 0, alpha: 0 };
for (const f of fs.readdirSync(path.join(ROOT, "src/data")).filter((x) => x.endsWith("-case-study.ts"))) {
  let study;
  try { study = Object.values(load("src/data/" + f)).find((v) => v && typeof v === "object" && Array.isArray(v.sections)); } catch (e) { continue; }
  if (!study) continue;
  const list = [], seen = new Map();
  const add = (src, alt) => {
    if (!src) return;
    /* a cover reel names its frames before the sections describe them,
       so a picture met first without words takes them when it comes round */
    if (seen.has(src)) { const had = seen.get(src); if (had && !had.alt && alt) had.alt = alt; return; }
    seen.set(src, null);
    const d = imageDimensions[src];
    if (!d) return;
    if (d[0] < 1100) { dropped.small++; return; }
    if (hasAlpha(src)) { dropped.alpha++; return; }
    const pic = { src, alt: alt || "", w: d[0], h: d[1] };
    seen.set(src, pic); list.push(pic);
  };
  if (homePic[study.slug]) add(homePic[study.slug].src, homePic[study.slug].alt);
  /* a picture is a string anywhere: a field beside its alt, or one of a
     list (a cover reel's frames are a plain list of paths) */
  const walk = (v, alt) => {
    if (typeof v === "string") { if (/^\/case-studies\/.+\.(jpe?g|png|webp|avif)$/i.test(v)) add(v, alt); return; }
    if (Array.isArray(v)) return v.forEach((x) => walk(x, ""));
    if (!v || typeof v !== "object") return;
    for (const [k, x] of Object.entries(v)) walk(x, typeof x === "string" ? v.alt || v[k + "Alt"] || v.caption || "" : "");
  };
  walk(study.sections);
  pictures[study.slug] = list;
}
const picFile = path.join(ROOT, "public/lab/scroll-concepts/pictures.js");
fs.writeFileSync(picFile, "/* generated by scripts/lib/scroll-concepts-studies.mjs from src/data; do not edit by hand */\nwindow.PICTURES = "
  + JSON.stringify(pictures) + ";\n");
console.log("wrote", path.relative(ROOT, picFile), fs.statSync(picFile).size, "bytes;",
  Object.values(pictures).reduce((n, l) => n + l.length, 0), "pictures across", Object.keys(pictures).length,
  "studies; left out", dropped.small, "under 1,100 wide and", dropped.alpha, "with transparency");
